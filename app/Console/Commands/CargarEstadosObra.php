    public function handle(): int
    {
        $dry = (bool) $this->option('dry-run');

        $porEstado = array_count_values(self::ESTADOS);
        ksort($porEstado);
        $desglose = collect($porEstado)->map(fn ($n, $e) => "$e: $n")->implode(', ');
        $this->info(sprintf('%s%d OT en el listado (%s).',
            $dry ? '[DRY-RUN] ' : '', count(self::ESTADOS), $desglose));

        if ($dry) {
            $existentes = ObraEstado::whereIn('codigo_proyecto', array_keys(self::ESTADOS))
                ->pluck('estado', 'codigo_proyecto');
            $nuevas = 0; $cambian = 0; $iguales = 0;
            foreach (self::ESTADOS as $cod => $estado) {
                if (! isset($existentes[$cod]))      $nuevas++;
                elseif ($existentes[$cod] !== $estado) $cambian++;
                else                                   $iguales++;
            }
            $this->line("  Nuevas: $nuevas · Cambian: $cambian · Ya iguales: $iguales");
            $this->comment('Sin cambios (dry-run). Quita --dry-run para aplicar.');
            return self::SUCCESS;
        }

        $n = 0;
        DB::transaction(function () use (&$n) {
            foreach (self::ESTADOS as $cod => $estado) {
                ObraEstado::updateOrCreate(['codigo_proyecto' => $cod], ['estado' => $estado]);
                $n++;
            }
        });

        $this->info("Aplicados: $n estado(s).");
        $resumen = ObraEstado::selectRaw('estado, COUNT(*) as n')->groupBy('estado')->pluck('n', 'estado');
        $this->line('obras_estado ahora: '.$resumen->map(fn ($n, $e) => "$e=$n")->implode(' '));
        return self::SUCCESS;
    }
